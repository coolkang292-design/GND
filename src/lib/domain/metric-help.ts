export type MetricHelpKey = keyof typeof HELP;

export const METRIC_HELP: Record<string, MetricHelp> = HELP;

/**
 * 화면이 요청한 키의 설명을 순서대로 낸다.
 *
 * ⚠️ **없는 키는 던진다.** 조용히 건너뛰면 "패널에는 있는데 설명이 없는 지표"가
 * 생기고 아무도 모른다. 테스트가 이 던지기를 잡는다.
 */
export function metricHelpFor(
  keys: readonly MetricHelpKey[],
): (MetricHelp & { key: string })[] {
  return keys.map((key) => {
    const help = METRIC_HELP[key];
    if (!help) throw new Error(`지표 설명이 없는 키: ${key}`);
    return { key, ...help };
  });
}
