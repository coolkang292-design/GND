/**
 * 차단의 순수 규칙 (0089).
 *
 * ⚠️ **신고 관련 코드가 여기 있었는데 걷어냈다** (2026-08-31, first-principles).
 *    사유 목록·글자수 검증이 있었지만, 그 값들은 **읽을 사람이 있을 때만** 의미가
 *    있다. GND에는 조치 수단이 하나도 없다(ban·suspend·kick RPC 없음, /admin에
 *    조치 버튼 없음). 그래서 신고는 "접수했다"는 약속만 하고 아무 일도 안 하는
 *    창구였다. 차단이 실제 일을 다 한다.
 *
 *    `user_reports` 테이블과 `report_user` RPC는 0089에 들어간 채 **잠들어 있다.**
 *    조치 수단이 생기거나 앱스토어 심사(Apple 1.2)가 필요해지면 되살린다.
 */

/**
 * 차단 버튼의 문구·설명.
 *
 * 무엇이 일어나는지 **정확히** 적는다. "차단하시겠어요?"만 띄우면 사용자는
 * 크루 관계가 끊기는지, 상대가 아는지를 모른 채 누른다. 둘 다 아니라는 것이
 * 이 기능의 핵심 성질이라 그 자리에서 말해 준다.
 */
export function blockConfirmCopy(nickname: string): {
  title: string;
  body: string;
  confirm: string;
} {
  return {
    title: `${nickname}님을 차단할까요?`,
    body:
      "서로의 게시물·댓글·응원이 보이지 않게 되고, 크루 신청도 오갈 수 없어요. " +
      "상대에게는 차단 사실이 알려지지 않아요. 크루 관계는 그대로 남아 있어서 " +
      "차단을 풀면 원래대로 돌아와요.",
    confirm: "차단하기",
  };
}
