/** 날짜 문자열 해시로 변형 하나 선택 — 같은 날엔 고정, 날마다 로테이션 */
export function pickByDay<T>(variants: T[], todayKey: string): T {
  let h = 0;
  for (const c of todayKey) h = (h * 31 + c.charCodeAt(0)) % 997;
  return variants[h % variants.length];
}
