// 손실회피 + 능청 유머: 잃을 숫자(n일)는 정확히 찌르되, 약올리듯 능청스럽게.
// 단계마다 변형 여러 개 — 날짜 기반으로 하루마다 돌아가며 나온다(렌더 중 랜덤은
// 하이드레이션 불일치·재렌더마다 문구 바뀜 문제가 있어 결정적 로테이션 사용).
//
// ── 단계별 심리 기제 (2026-08-13 사용자 지시 "손실회피와 동기 부여를 조합") ──
//
// ⚠️ **단계마다 다른 기제를 쓴다. 전부 공포로 밀면 안 된다.** 손실 회피만 반복하면
// ① 아직 여유 있는 단계에서 거짓말이 되고 ② 매일 겁주는 알림은 꺼진다. 그래서
// 위험이 낮은 단계는 **접근 동기**(다가가는 힘)를, 높은 단계는 **회피 동기**를 쓴다.
//
// | 단계 | 상태 | 주 기제 | 왜 |
// |---|---|---|---|
// | `today_done` | 오늘 완료 | 목표 구배(goal-gradient) | 잃을 게 없다. 다음 한 칸을 보여주는 게 유일한 지렛대 |
// | `d4` | 어제 운동 | 자이가르닉 + 목표 구배 | 아직 4일 여유 — 위협은 거짓이다. "빈 칸"과 "다음 숫자"로 민다 |
// | `d3` | 2일 쉼 | 보유 효과 + 매몰 노력 | 이미 **가진** n일과 그걸 쌓는 데 든 수고를 상기시킨다 |
// | `d2` | 3일 쉼 | 손실 회피 + 자기효능 | 잃을 양을 못 박되 "30분이면"으로 문턱을 낮춘다 |
// | `d1` | 4일 쉼 | 손실 회피 최대 + 실행 의도 | 마지막 날. 구체적 행동(지금·30분)까지 붙인다 |
// | `expired` | 소멸 | 새 출발 효과(fresh start) | 이미 잃었다 — 남은 지렛대는 다시 시작하는 문턱뿐 |
//
// 근거 이론: 전망 이론(Kahneman·Tversky, 손실은 이득보다 크게 느껴진다),
// 보유 효과(Thaler), 목표 구배(Hull·Kivetz), 자이가르닉 효과(미완결이 기억에 남는다),
// 실행 의도(Gollwitzer, 언제·무엇을 정해두면 실행률이 오른다),
// 자기효능감(Bandura, 할 수 있다고 느낄 때 시도한다),
